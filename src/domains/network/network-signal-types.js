/**
 * Signal type registry — 6 signal types confirmed by NETWORK ASSET COUNCIL.
 * @readonly
 */
export const SIGNAL_TYPES = Object.freeze({
  SYMPTOM:   'SYMPTOM',   // Primary signal — symptom observations
  PAIN:      'PAIN',      // Quantitative signal — pain level / type
  MENSTRUAL: 'MENSTRUAL', // Cycle signal — menstrual phase / flow
  EMOTION:   'EMOTION',   // State signal — emotional state (Wave2 activation)
  SLEEP:     'SLEEP',     // Recovery signal — sleep quality / duration
  EXPOSURE:  'EXPOSURE',  // Intervention signal — food / supplement (BD-005: Exposure Signal)
});

/**
 * Menstrual phase registry — used for phase context on edges (Wave2) and signal metadata.
 * UNKNOWN is the default when phase cannot be determined.
 * @readonly
 */
export const MENSTRUAL_PHASES = Object.freeze({
  MENSTRUAL:  'MENSTRUAL',   // Day 1–5
  FOLLICULAR: 'FOLLICULAR',  // Day 6–12
  OVULATION:  'OVULATION',   // Day 13–16
  LUTEAL:     'LUTEAL',      // Day 17–28
  UNKNOWN:    'UNKNOWN',
});

/**
 * FeatureVector version identifier.
 * BD-010: must be bumped when FeatureVector dimensions are expanded.
 * BD-011: all edges generated by EdgeGenerator must carry this version.
 * Wave1 = '1' (8-dimensional, current).
 * Wave2 = '2' (12-dimensional, planned).
 * @readonly
 */
export const VECTOR_VERSION = '1';

/**
 * Signal normalization units — documents how rawValue maps to normalizedValue.
 * @readonly
 */
export const SIGNAL_UNITS = Object.freeze({
  SYMPTOM:   'severity_0_10',   // rawValue 0–10 → normalizedValue = rawValue / 10
  PAIN:      'pain_level_0_10', // rawValue 0–10 → normalizedValue = rawValue / 10
  MENSTRUAL: 'flow_level_0_3',  // rawValue 0–3 → normalizedValue = rawValue / 3
  EMOTION:   'mood_0_10',       // rawValue 0–10 → normalizedValue = rawValue / 10 (Wave2)
  SLEEP:     'hours_0_12',      // rawValue hours → normalizedValue = clamp(rawValue / 8, 0, 1)
  EXPOSURE:  'count_0_10',      // rawValue count → normalizedValue = clamp(rawValue / 5, 0, 1)
});

/** Convenience sets for O(1) membership checks. */
export const SIGNAL_TYPE_VALUES    = Object.freeze(new Set(Object.values(SIGNAL_TYPES)));
export const MENSTRUAL_PHASE_VALUES = Object.freeze(new Set(Object.values(MENSTRUAL_PHASES)));
