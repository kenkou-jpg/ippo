// signal-intelligence-v2-service.js — PR-050: Signal Intelligence V2.
// Rebuilds Signal Intelligence (aggregation / trend / timeline / summary) on top of
// PERSISTED signals from NetworkSignalPersistenceServiceV2 (BD-022 Wave2 store).
//
// BD-024: Emotion Signal is NOW included in all aggregations (Wave2 activation).
//         BD-024 prohibited Wave1 Emotion Signal generation. PR-043 activated it.
//         PR-050 confirms: EMOTION signals from persistent store flow into V2 aggregation.
// BD-038: Rule-based computation only — no AI, no LLM, no inference.
// BD-022: Signal source = NetworkSignalPersistenceServiceV2 (Supabase/adapter-backed).
//
// Key additions over Wave1:
//   1. Signal source = persistent store (not calller-provided in-memory array)
//   2. aggregateByPhase() — menstrual phase × signal type breakdown
//   3. Emotion Signal in trend, timeline, summary (BD-024 Wave2 active)
//   4. createDailySnapshot() — BD-018 compliant daily snapshot from persisted signals

import { SIGNAL_TYPES, MENSTRUAL_PHASES } from './network-signal-types.js';
import { SNAPSHOT_SCHEDULE }              from './signal-snapshot-types.js';

// ── SignalIntelligenceV2Service ───────────────────────────────────────────────

export class SignalIntelligenceV2Service {
  #persistenceService;    // NetworkSignalPersistenceServiceV2 — source of truth
  #aggregationService;    // SignalAggregationService (Wave1 stateless)
  #trendService;          // SignalTrendService (Wave1 stateless)
  #timelineService;       // SignalTimelineService (Wave1 stateless)
  #summaryService;        // SignalSummaryService (Wave1 stateless)
  #snapshotService;       // SignalSnapshotService (Wave1) — for daily snapshot writes

  /**
   * @param {{
   *   persistenceService: object,
   *   aggregationService: object,
   *   trendService:       object,
   *   timelineService:    object,
   *   summaryService:     object,
   *   snapshotService:    object,
   * }} deps
   */
  constructor({
    persistenceService,
    aggregationService,
    trendService,
    timelineService,
    summaryService,
    snapshotService,
  }) {
    if (!persistenceService) throw new Error('[SignalIntelligenceV2Service] persistenceService is required');
    if (!aggregationService) throw new Error('[SignalIntelligenceV2Service] aggregationService is required');
    if (!trendService)       throw new Error('[SignalIntelligenceV2Service] trendService is required');
    if (!timelineService)    throw new Error('[SignalIntelligenceV2Service] timelineService is required');
    if (!summaryService)     throw new Error('[SignalIntelligenceV2Service] summaryService is required');
    if (!snapshotService)    throw new Error('[SignalIntelligenceV2Service] snapshotService is required');

    this.#persistenceService = persistenceService;
    this.#aggregationService = aggregationService;
    this.#trendService       = trendService;
    this.#timelineService    = timelineService;
    this.#summaryService     = summaryService;
    this.#snapshotService    = snapshotService;
  }

  // ── Persisted signal access ───────────────────────────────────────────────

  /**
   * Return all signals from the persistent store (Wave2 Supabase-backed).
   * BD-022: source is NetworkSignalPersistenceServiceV2.
   * BD-024: Emotion signals generated by PR-043 are included.
   * @returns {object[]}
   */
  getAllSignals() {
    return this.#persistenceService.findAll();
  }

  // ── Aggregation (BD-024: all 6 signal types) ─────────────────────────────

  /**
   * Aggregate all persisted signals by type and day.
   * BD-024: EMOTION signals are included (Wave2 active).
   * @returns {object}  AggregationResult: { byType, byDay, total }
   */
  aggregate() {
    return this.#aggregationService.aggregate(this.getAllSignals());
  }

  /**
   * Aggregate persisted signals of a single type.
   * @param {string} signalType  One of SIGNAL_TYPES values
   * @returns {object}  AggregationStats: { count, sum, average, min, max, latest }
   */
  aggregateByType(signalType) {
    return this.#aggregationService.aggregateByType(this.getAllSignals(), signalType);
  }

  /**
   * Phase-based aggregation — NEW in V2.
   * Groups persisted signals by menstrualPhase, then computes average normalizedValue
   * per signal type within each phase.
   *
   * BD-024: EMOTION signals included.
   * Output shape:
   *   {
   *     [phase: MENSTRUAL_PHASES]: {
   *       count: number,
   *       byType: { [SIGNAL_TYPES]: { count, average } }
   *     }
   *   }
   *
   * @returns {Readonly<object>}
   */
  aggregateByPhase() {
    const signals = this.getAllSignals();

    // Initialize all phase buckets
    const result = {};
    for (const phase of Object.values(MENSTRUAL_PHASES)) {
      result[phase] = { count: 0, byType: {} };
      for (const type of Object.values(SIGNAL_TYPES)) {
        result[phase].byType[type] = { count: 0, sum: 0, average: 0 };
      }
    }

    for (const signal of signals) {
      if (!signal || typeof signal !== 'object') continue;
      const phase = signal.menstrualPhase ?? MENSTRUAL_PHASES.UNKNOWN;
      const type  = signal.signalType;

      const bucket = result[phase] ?? result[MENSTRUAL_PHASES.UNKNOWN];
      bucket.count++;

      if (type && bucket.byType[type] !== undefined) {
        const typeBucket = bucket.byType[type];
        typeBucket.count++;
        typeBucket.sum += signal.normalizedValue ?? 0;
      }
    }

    // Finalize averages
    for (const phase of Object.values(MENSTRUAL_PHASES)) {
      for (const type of Object.values(SIGNAL_TYPES)) {
        const b = result[phase].byType[type];
        b.average = b.count > 0 ? Math.round((b.sum / b.count) * 1000) / 1000 : 0;
        delete b.sum; // internal only
      }
    }

    return Object.freeze(result);
  }

  // ── Trend (BD-024: EMOTION now included as trend target) ─────────────────

  /**
   * Compute trend for a specific signal type from persisted signals.
   * BD-024: EMOTION is a valid signalType for V2 trend analysis.
   * @param {string} signalType
   * @returns {object}  TrendResult
   */
  trend(signalType) {
    return this.#trendService.trend(this.getAllSignals(), signalType);
  }

  /**
   * Compute trends for all signal types present in persisted signals.
   * BD-024: EMOTION signals will appear in result if any exist.
   * @returns {Record<string, object>}  { [signalType]: TrendResult }
   */
  trendAll() {
    return this.#trendService.trendAll(this.getAllSignals());
  }

  // ── Timeline ──────────────────────────────────────────────────────────────

  /**
   * Build chronological timeline from all persisted signals.
   * @returns {object}  TimelineResult: { days, totalDays, totalSignals, from, to }
   */
  buildTimeline() {
    return this.#timelineService.buildTimeline(this.getAllSignals());
  }

  /**
   * Build timeline filtered to a date range.
   * @param {string} fromDate  YYYY-MM-DD
   * @param {string} toDate    YYYY-MM-DD
   * @returns {object}
   */
  buildTimelineRange(fromDate, toDate) {
    return this.#timelineService.buildTimelineRange(this.getAllSignals(), fromDate, toDate);
  }

  /**
   * Build timeline filtered to a single signal type.
   * @param {string} signalType
   * @returns {object}
   */
  buildTimelineByType(signalType) {
    return this.#timelineService.buildTimelineByType(this.getAllSignals(), signalType);
  }

  // ── Summary ───────────────────────────────────────────────────────────────

  /**
   * Generate a full summary from all persisted signals.
   * BD-024: emotionCount and EMOTION latestSignal are now populated.
   * BD-018: summary includes generatedAt.
   * @returns {object}  SignalSummary
   */
  summarize() {
    return this.#summaryService.summarize(this.getAllSignals());
  }

  // ── Snapshot (BD-018 / PR-035 extension) ─────────────────────────────────

  /**
   * Create a daily snapshot from all persisted signals.
   * BD-018: snapshot includes generatedAt + vectorVersion.
   * @param {string} [schedule]  DAILY | WEEKLY | MANUAL
   * @returns {Readonly<object>}  SignalSnapshot
   */
  createDailySnapshot(schedule = SNAPSHOT_SCHEDULE.DAILY) {
    return this.#snapshotService.createSnapshot(this.getAllSignals(), schedule);
  }

  // ── V2 diagnostics ────────────────────────────────────────────────────────

  /**
   * Return V2 health status including BD-024 compliance confirmation.
   * @returns {Readonly<object>}
   */
  getV2Status() {
    const signals     = this.getAllSignals();
    const typeCounts  = {};
    for (const type of Object.values(SIGNAL_TYPES)) {
      typeCounts[type] = signals.filter(s => s?.signalType === type).length;
    }

    return Object.freeze({
      version:            'V2',
      totalPersisted:     signals.length,
      signalTypeCounts:   Object.freeze(typeCounts),
      emotionIncluded:    true,  // BD-024: Wave2 activation confirmed
      allSixTypesTracked: Object.keys(SIGNAL_TYPES).length === 6,
      persistenceSource:  'NetworkSignalPersistenceServiceV2',
    });
  }
}
